// Bundles src/main.ts and copies public/ into dist/ (served by GitHub Pages and packaged by Capacitor).
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const dist = here('../dist/');
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

await build({
  entryPoints: [here('../src/main.ts')],
  bundle: true,
  format: 'esm',
  target: ['es2022', 'chrome100', 'safari16'],
  outfile: `${dist}app.js`,
  minify: process.env.NODE_ENV !== 'development',
  sourcemap: false,
  legalComments: 'linked',
  // The crypto library's dependencies live in ../reference/node_modules.
  nodePaths: [here('../../reference/node_modules'), here('../node_modules')],
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'info',
});

cpSync(here('../public/'), dist, { recursive: true });

// Service worker with a cache name tied to the bundle contents, so updates take effect.
const hash = createHash('sha256');
for (const f of ['index.html', 'boot-check.js', 'app.js', 'styles.css', 'manifest.webmanifest']) hash.update(readFileSync(`${dist}${f}`));
const version = hash.digest('hex').slice(0, 12);
writeFileSync(
  `${dist}sw.js`,
  `// Generated by scripts/build.mjs
const CACHE = 'sma-${version}';
const SHELL = ['./', 'index.html', 'boot-check.js', 'app.js', 'styles.css', 'manifest.webmanifest', 'icon.svg', 'icon-192.png', 'icon-512.png'];
self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) => e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`,
);
console.log(`dist ready (cache ${version})`);
