/**
 * The app computes exactly what the platform computes: payments/mobile/conformance/vectors.json
 * is generated by the Go platform (cmd/conformance) and checked by the JavaScript spec tools.
 */
class ConformanceTest {
    private val json = Json { ignoreUnknownKeys = true }
    private val v: JsonObject = json.parseToJsonElement(File(System.getProperty("conformance.vectors")).readText()).jsonObject

    private fun JsonObject.s(k: String) = this[k]!!.jsonPrimitive.content
    private fun event(o: JsonObject) = json.decodeFromJsonElement(Event.serializer(), o)

    @Test fun bip340SignaturesMatchByteForByte() {
        for (x in v["bip340"]!!.jsonArray.map { it.jsonObject }) {
            val k = NostrKeys(x.s("secret").hexToBytes())
            assertEquals(x.s("pubkey"), k.publicKeyHex)
            assertEquals(x.s("signature"), k.signSchnorr(x.s("message").hexToBytes(), x.s("aux").hexToBytes()).toHex())
        }
    }

    @Test fun testKeysNpubAndNsec() {
        for (x in v["test_keys"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(x.s("secret"), sha256("goonerspay-spec/test-key/" + x.s("role")).toHex())
            val k = NostrKeys(x.s("secret").hexToBytes())
            assertEquals(x.s("npub"), k.npub)
            assertEquals(x.s("nsec"), k.nsec())
            assertEquals(x.s("secret"), NostrKeys.fromNsec(x.s("nsec")).exportSecret().toHex())
            assertEquals(x.s("pubkey"), Bech32.decode("npub", x.s("npub")).toHex())
        }
    }

    @Test fun nip01SerializationAndSignatures() {
        val device = NostrKeys(sha256("goonerspay-spec/test-key/merchant-device-android"))
        for (x in v["events"]!!.jsonArray.map { it.jsonObject }) {
            val ev = event(x["event"]!!.jsonObject)
            assertEquals(x.s("name"), x.s("serialization"), ev.serialize())
            assertEquals(ev.id, ev.computeId())
            assertTrue(ev.verify())
            val resigned = ev.copy(id = "", sig = "", pubkey = "").signedBy(device, x.s("aux").hexToBytes())
            assertEquals(ev.sig, resigned.sig)
            assertFalse(ev.copy(content = ev.content + " ").verify())
        }
    }

    @Test fun nip98HeaderIsReproduced() {
        val x = v["nip98"]!!.jsonObject
        val ev = event(x["event"]!!.jsonObject)
        val device = NostrKeys(sha256("goonerspay-spec/test-key/merchant-device-android"))
        val rebuilt = Nip98.event(device, x.s("method"), x.s("url"), x.s("body").toByteArray(), ev.createdAt, x.s("aux").hexToBytes())
        assertEquals(ev, rebuilt)
        assertEquals(x.s("authorization_header"), Nip98.header(rebuilt))
    }

    @Test fun jwkThumbprint() {
        val x = v["jwk_thumbprint"]!!.jsonObject
        assertEquals(x.s("thumbprint"), json.decodeFromJsonElement(Jwk.serializer(), x["jwk"]!!).thumbprint())
    }

    @Test fun deviceListIsReproduced() {
        val x = v["device_list"]!!.jsonObject
        val ev = event(x["event"]!!.jsonObject)
        val root = NostrKeys(sha256("goonerspay-spec/test-key/merchant-root"))
        val entries = ev.tags.filter { it[0] == "device" }.map { DeviceList.Entry(it[1], it[2], it[3]) }
        assertEquals(ev, DeviceList.event(root, ev.tag("merchant")!![1], entries, ev.createdAt, x.s("aux").hexToBytes()))
    }

    @Test fun canonicalJson() {
        for (x in v["canonical_json"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(x.s("canonical"), CanonicalJson.encode(json.parseToJsonElement(x.s("json"))))
        }
    }

    @Test fun journalEntriesAreReproduced() {
        val j = v["journal"]!!.jsonObject
        val device = NostrKeys(sha256("goonerspay-spec/test-key/" + j.s("device_role")))
        val entries = j["entries"]!!.jsonArray.map { it.jsonObject }
        for (x in entries) {
            val ev = event(x["event"]!!.jsonObject)
            assertEquals(ev.content, CanonicalJson.encode(x["fields"]!!))
            assertEquals(ev, ev.copy(id = "", sig = "", pubkey = "").signedBy(device, x.s("aux").hexToBytes()))
        }
        // The journal itself writes the first entry byte for byte, before any key is unwrapped.
        val first = event(entries[0]["event"]!!.jsonObject)
        val journal = Journal(MemoryJournalStore(), device.publicKeyHex, first.tag("merchant")!![1], "0.1.0", { first.createdAt }, java.time.ZoneOffset.ofHours(-3))
        assertEquals(first.id, journal.append("session_start").id)
    }

    @Test fun deviceRiskModel() {
        val x = v["device_risk"]!!.jsonObject
        assertEquals(x.s("model"), br.com.gooners.pay.core.risk.DeviceModel.NAME)
        assertEquals(x["max_signals"]!!.jsonPrimitive.int, br.com.gooners.pay.core.risk.DeviceModel.MAX_SIGNALS)
        assertEquals(x["weights"]!!.jsonObject.mapValues { it.value.jsonPrimitive.int }, br.com.gooners.pay.core.risk.DeviceModel.WEIGHTS)
        for (c in x["cases"]!!.jsonArray) {
            val o = c.jsonObject
            val got = br.com.gooners.pay.core.risk.DeviceModel.score(o["signals"]!!.jsonArray.map { it.jsonPrimitive.content })
            assertEquals(o.toString(), o["score_milli"]!!.jsonPrimitive.int, got.milli)
            assertEquals(o.toString(), o["sent"]!!.jsonArray.map { it.jsonPrimitive.content }, got.signals)
        }
    }

    @Test fun keyAttestationChallenge() {
        val x = v["key_attestation_challenge"]!!.jsonObject
        assertEquals(x.s("challenge"), br.com.gooners.pay.core.auth.KeyAttestation.challenge(x.s("device_pubkey")).toHex())
    }

    @Test fun sandboxCardFormat() {
        val x = v["dev_card"]!!.jsonObject
        val card = json.decodeFromString(DevCard.serializer(), x.s("plaintext"))
        val blob = DevFormat.encrypt(x.s("key").hexToBytes(), x.s("ksn"), card, x.s("nonce").hexToBytes())
        assertEquals(x.s("ciphertext_base64"), Base64.getEncoder().encodeToString(blob))
        assertEquals(card, DevFormat.decrypt(x.s("key").hexToBytes(), x.s("ksn"), Base64.getDecoder().decode(x.s("ciphertext_base64"))))
    }

    @Test fun brCodes() {
        for (x in v["brcode"]!!.jsonArray.map { it.jsonObject }) {
            val b = BrCode.decode(x.s("code"))
            assertEquals(x["dynamic"]!!.jsonPrimitive.boolean, b.dynamic)
            assertEquals(x.s("amount"), b.amount)
            assertEquals(x.s("merchant_name"), b.merchantName)
            if (b.dynamic) assertEquals(x.s("url"), b.url) else assertEquals(x.s("key"), b.key)
            val broken = x.s("code").dropLast(1) + if (x.s("code").last() == '0') '1' else '0'
            assertTrue(runCatching { BrCode.decode(broken) }.isFailure)
        }
    }

    @Test fun money() {
        for (x in v["money"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(x.s("display"), Money(x["centavos"]!!.jsonPrimitive.long).format())
        }
    }

    /** Every signed example of the specification verifies here too. */
    @Test fun specExamplesVerify() {
        var n = 0
        File(System.getProperty("nostr.examples")).listFiles()!!.filter { it.name.endsWith(".json") && it.name != "keys.json" }.forEach { f ->
            fun visit(e: kotlinx.serialization.json.JsonElement) {
                when (e) {
                    is JsonObject -> {
                        if (e["sig"] != null && e["id"] != null && e["kind"] != null) {
                            assertTrue("${f.name}: ${e["id"]}", event(e).verify())
                            n++
                        }
                        e.values.forEach(::visit)
                    }
                    is kotlinx.serialization.json.JsonArray -> e.forEach(::visit)
                    else -> {}
                }
            }
            visit(json.parseToJsonElement(f.readText()))
        }
        assertTrue("only $n events", n >= 15)
    }
}
